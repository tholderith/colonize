def width(t, sp=1):
    return len(t) * (5 + sp) - sp
def text(im, x, y, t, col, shadow=None, sp=1):
    """draw onto PIL RGBA image im at native pixel coords."""
    px = im.load()
    def put(a, b, c):
        if 0 <= a < im.width and 0 <= b < im.height: px[a, b] = tuple(c) + (255,)
    for pas in ([shadow] if shadow else []) + [col]:
        ox = 1 if (pas is shadow and shadow) else 0
        for i, ch in enumerate(t.upper()):
            g = G.get(ch, G[' ']).split('/')
            for r, row in enumerate(g):
                for c, v in enumerate(row):
                    if v == '1': put(x + i * (5 + sp) + c + ox, y + r + ox, pas)
